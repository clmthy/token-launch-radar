// Token Radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// the early radar: every pre-token protocol below the watchlist floor that passes the watchlist's
// own exclusion rule (no Bridge / Canonical Bridge / Liquid Staking / Liquid Restaking / Restaked
// BTC / CEX category, no versioned name, no wrapped / staked / staking word, no exchange-prefixed
// name). A wrapped, staked or bridged product of a token that already trades is not a token that
// does not exist yet, so the early rows are held to the same bar as the watchlist. A protocol is
// pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board.
//
// Implied value follows only from the snapshot's own figures. No protocol name is ever
// special-cased: the same function scores every row.
//
//   base      = tvl_usd x BASE_MULTIPLE
//   growth    = clamp(change_7d, -50, 200) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT                 (0.60 .. 2.60)
//   breakout  = 1 + BREAKOUT_WEIGHT x min(max(change_7d, 0), 200) / 200
//               only when age_days < BREAKOUT_AGE_DAYS and change_7d > BREAKOUT_GROWTH_PCT,
//               else 1                                             (1.00 .. 1.50)
//   maturity  = MATURITY_FLOOR + min(age_days, MATURITY_DAYS) / MATURITY_DAYS x MATURITY_RANGE
//               (age_days unknown: UNKNOWN_AGE_DAYS)                (0.60 .. 1.00)
//   category  = 1 + CATEGORY_WEIGHT x tanh(log2(tvl_usd / categoryMedian) / 2)
//               categoryMedian is the median TVL of the snapshot's pre-token protocols in the
//               same category, so a protocol is measured against its own kind  (0.80 .. 1.20)
//   chain     = 1 + CHAIN_PER x log2(1 + chains.length)             (1.04 .. ~1.22)
//   implied   = max(1, round(base x growthMult x breakout x maturity x category x chain))
//
// Why these factors: TVL anchors what a launch could be worth; seven-day growth is the momentum
// the snapshot actually carries, and the 200% cap keeps one listing spike from buying the board;
// the breakout factor is the earliness signal — a young protocol already growing fast is the
// future airdrop the radar exists to find early, and it only fires on young, growing rows; maturity
// credits a protocol that has run a long time with no token (established, still to come); the
// category factor stops a big DEX from outranking a category-leading vault on size alone; the chain
// factor is a small reach tiebreaker for protocols deployed on more chains.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

